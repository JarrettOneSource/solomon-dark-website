export function nativeGravestoneShadowOutline(variant: number): Vec2[] {
  return selected(GRAVESTONE, variant, 'Gravestone')
}

export function nativeFencepostShadowOutline(selector: number, style: 0 | 1): Vec2[] {
  const source = selected(FENCEPOST_FULL, selector % 7, 'Fencepost')
  return style === 0
    ? source
    : source.map(({ x, y }) => ({ x: x * 0.45, y: y * 0.45 - 1 }))
}

export function nativeMonumentShadowOutline(variant: number): Vec2[] {
  return selected(MONUMENT, variant, 'Monument')
}

export function nativeBuildingShadowOutline(variant: number): Vec2[] {
  return selected(BUILDING, variant, 'Building')
}

export function nativeGoodieShadowOutline(subtype: number): Vec2[] {
  if (subtype !== 0) {
    throw new RangeError(`Unsupported native Goodie complex-shadow subtype ${subtype}.`)
  }
  return GOODIE_ZERO.map(([x, y]) => ({ x, y }))
}

function selected(
  rows: readonly (readonly NativePoint[])[],
  index: number,
  family: string,
): Vec2[] {
  const row = rows[index]
  if (!row) throw new RangeError(`Unsupported native ${family} complex-shadow variant ${index}.`)
  return row.map(([x, y]) => ({ x, y }))
}
