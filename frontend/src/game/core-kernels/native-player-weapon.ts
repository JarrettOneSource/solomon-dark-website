import weaponProgram from '../../assets/game/player-weapon-attachment-program.json' with { type: 'json' }

export type NativePlayerWeaponKind = 'staff' | 'wand' | null
export type PlayerWandAttachmentPose = 0 | 1 | 2

export function playerWandPrimaryPose(
  actionTick: number,
  channelActive: boolean,
  element: WizardElement,
): PlayerWandAttachmentPose {
  const rate = element === 'ether' ? Math.fround(0.1) : Math.fround(Math.fround(0.1) * 0.75)
  return actionTick > 0 && !channelActive && Math.fround(actionTick * rate) < 2 ? 1 : 0
}

export function playerHandSpellEmitterOffset(headingIndex: number): Vector2 {
  const facing = ((Math.round(headingIndex) % 24) + 24) % 24
  const point = weaponProgram.bare[facing]!
  return { x: point[0]!, y: point[1]! }
}

export function playerWandSpellEmitterOffset(
  headingIndex: number,
  pose: PlayerWandAttachmentPose,
): Vector2 {
  const facing = ((Math.round(headingIndex) % 24) + 24) % 24
  const point = weaponProgram.wand[pose]![facing]!.end
  return { x: point[0]!, y: point[1]! }
}

