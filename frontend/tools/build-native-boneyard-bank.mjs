#!/usr/bin/env -S node --experimental-strip-types

import { createHash } from 'node:crypto'
import { readFile, writeFile } from 'node:fs/promises'
import { dirname, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

import { parseBoneyard } from '../src/editor/format/boneyard.ts'
import {
  boneyardGeometrySha256,
  projectBoneyard,
} from '../src/game/host/project-boneyard.ts'

const frontendRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const outputPath = resolve(
  frontendRoot,
  'src/game/host/native-generated-boneyards.ts',
)
const sources = process.argv.slice(2).map((source) => resolve(source))

if (sources.length === 0) {
  throw new Error('Pass one or more stock-generated .boneyard files.')
}

const templates = []
for (const sourcePath of sources) {
  const bytes = await readFile(sourcePath)
  const parsed = parseBoneyard(new Uint8Array(bytes))
  const scene = projectBoneyard(parsed)
  templates.push({
    sourceSha256: sha256(bytes),
    geometrySha256: boneyardGeometrySha256(scene),
    scene,
  })
}

const source = [
  '// Generated by tools/build-native-boneyard-bank.mjs from exact stock-generator outputs.',
  '// Do not hand-edit. Combat recipes and timelines are intentionally excluded.',
  '/* oxlint-disable no-loss-of-precision */',
  "import type { NativeBoneyardTemplate } from '../core-kernels/boneyard.ts'",
  '',
  `export const NATIVE_GENERATED_BONEYARDS: readonly NativeBoneyardTemplate[] = ${JSON.stringify(templates)}`,
  '',
].join('\n')

await writeFile(outputPath, source)
process.stdout.write(`${relative(process.cwd(), outputPath)}: ${templates.length} native layouts\n`)
for (const [index, template] of templates.entries()) {
  const scene = template.scene
  process.stdout.write(
    `${index + 1} ${template.sourceSha256} `
    + `${scene.objects.length} objects ${scene.sprites.length} sprites `
    + `${scene.roads.length} roads ${scene.fences.length} fences\n`,
  )
}

function sha256(value) {
  return createHash('sha256').update(value).digest('hex')
}
