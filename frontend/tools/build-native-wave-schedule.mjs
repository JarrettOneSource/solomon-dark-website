#!/usr/bin/env node

import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'

import { parseWaveText, validateWaves } from '../src/editor/waves.ts'

const args = parseArgs(process.argv.slice(2))
const input = resolve(args.input)
const output = resolve(args.output)
const bytes = await readFile(input)
const waves = parseWaveText(bytes.toString('utf8'))
const problems = validateWaves(waves)
if (problems.length > 0) throw new Error(problems.join('\n'))

const enemyRows = waves.flatMap((wave) => wave.groups.flatMap((group) => group.entries))
const source = `// Generated by tools/build-native-wave-schedule.mjs from the untouched retail
// data/wave.txt. Do not hand-edit schedule rows.

import type { WaveDef } from './boneyard-wave-schema.ts'

export const NATIVE_RETAIL_WAVES: readonly WaveDef[] = ${JSON.stringify(waves, null, 2)}
`
await mkdir(dirname(output), { recursive: true })
await writeFile(output, source, 'utf8')
console.log(`wrote ${output}: ${waves.length} waves, ${enemyRows.length} enemy rows`)

function parseArgs(tokens) {
  const values = {}
  for (let index = 0; index < tokens.length; index += 2) {
    const flag = tokens[index]
    const value = tokens[index + 1]
    if ((flag !== '--input' && flag !== '--output') || value === undefined) {
      throw new Error('usage: build-native-wave-schedule.mjs --input FILE --output FILE')
    }
    values[flag.slice(2)] = value
  }
  if (!values.input || !values.output) {
    throw new Error('usage: build-native-wave-schedule.mjs --input FILE --output FILE')
  }
  return values
}
