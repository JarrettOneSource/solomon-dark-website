#!/usr/bin/env node

import { createHash } from 'node:crypto'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'

import { parseWaveText, validateWaves } from '../src/editor/waves.ts'

const EXPECTED_SOURCE_SHA256 = '363a985d79dc3ca28fb5ce519f56c436f5269a9bea1bedc7d1a825e8139499fc'
const EXPECTED_SOURCE_BYTES = 29147
const EXPECTED_WAVES = 42
const EXPECTED_SPAWN_BUDGET = 918
const EXPECTED_GROUPS = 205
const EXPECTED_ROWS = 680

const args = parseArgs(process.argv.slice(2))
const input = resolve(args.input)
const output = resolve(args.output)
const bytes = await readFile(input)
const sha256 = createHash('sha256').update(bytes).digest('hex')
if (sha256 !== EXPECTED_SOURCE_SHA256 || bytes.length !== EXPECTED_SOURCE_BYTES) {
  throw new Error(
    `retail wave source mismatch: expected ${EXPECTED_SOURCE_BYTES} bytes / `
    + `${EXPECTED_SOURCE_SHA256}, found ${bytes.length} bytes / ${sha256}`,
  )
}

const waves = parseWaveText(bytes.toString('utf8'))
const problems = validateWaves(waves)
if (problems.length > 0) throw new Error(problems.join('\n'))

const groupCount = waves.reduce((total, wave) => total + wave.groups.length, 0)
const spawnBudget = waves.reduce((total, wave) => total + wave.spawn, 0)
const enemyRows = waves.flatMap((wave) => wave.groups.flatMap((group) => group.entries))
if (
  waves.length !== EXPECTED_WAVES
  || spawnBudget !== EXPECTED_SPAWN_BUDGET
  || groupCount !== EXPECTED_GROUPS
  || enemyRows.length !== EXPECTED_ROWS
) {
  throw new Error(
    `retail wave census mismatch: waves=${waves.length} spawn=${spawnBudget} `
    + `groups=${groupCount} rows=${enemyRows.length}`,
  )
}

const enemyRowCounts = Object.fromEntries(
  [...new Set(enemyRows.map((entry) => entry.enemy))]
    .sort()
    .map((enemy) => [
      enemy,
      enemyRows.filter((entry) => entry.enemy === enemy).length,
    ]),
)
const source = `// Generated by tools/build-native-wave-schedule.mjs from the untouched retail
// data/wave.txt. Do not hand-edit schedule rows.

import type { WaveDef } from './boneyard-wave-schema.ts'

export const NATIVE_RETAIL_WAVE_PROVENANCE = ${JSON.stringify({
  schema: 'solomon-dark-retail-wave-schedule-v1',
  sourceFilename: 'data/wave.txt',
  sourceBytes: bytes.length,
  sourceSha256: sha256,
  waveCount: waves.length,
  spawnBudget,
  groupCount,
  enemyRowCount: enemyRows.length,
  enemyRowCounts,
}, null, 2)} as const

export const NATIVE_RETAIL_WAVES: readonly WaveDef[] = ${JSON.stringify(waves, null, 2)}
`
await mkdir(dirname(output), { recursive: true })
await writeFile(output, source, 'utf8')
console.log(`wrote ${output}: ${waves.length} waves, ${enemyRows.length} enemy rows`)

function parseArgs(tokens) {
  const values = {}
  for (let index = 0; index < tokens.length; index += 2) {
    const flag = tokens[index]
    const value = tokens[index + 1]
    if ((flag !== '--input' && flag !== '--output') || value === undefined) {
      throw new Error('usage: build-native-wave-schedule.mjs --input FILE --output FILE')
    }
    values[flag.slice(2)] = value
  }
  if (!values.input || !values.output) {
    throw new Error('usage: build-native-wave-schedule.mjs --input FILE --output FILE')
  }
  return values
}
