#!/usr/bin/env -S node --experimental-strip-types

import { createHash } from 'node:crypto'
import { readFile, writeFile } from 'node:fs/promises'
import { dirname, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

import { parseBoneyard } from '../src/editor/format/boneyard.ts'
import {
  SOLOMON_DIG_FRAME_PROGRAM,
  boneyardGeometrySha256,
  projectBoneyard,
} from '../src/game/host/project-boneyard.ts'

const frontendRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const outputPath = resolve(frontendRoot, 'src/game/host/stock-tutorial-boneyard.ts')
const sourcePath = resolve(process.argv[2] ?? '')

if (!process.argv[2]) {
  throw new Error('Pass the stock data/levels/tutorial.boneyard path.')
}

const bytes = await readFile(sourcePath)
const projected = projectBoneyard(parseBoneyard(new Uint8Array(bytes)))
const solomonPosition = Object.freeze({
  x: 1021.53564453125,
  y: 1170.36669921875,
})
const scene = Object.freeze({
  ...projected,
  solomonDig: Object.freeze({
    frameProgram: SOLOMON_DIG_FRAME_PROGRAM,
    gravePosition: Object.freeze({
      x: solomonPosition.x - 10,
      y: solomonPosition.y - 113,
    }),
    lanternPosition: Object.freeze({
      x: solomonPosition.x - 65,
      y: solomonPosition.y - 40,
    }),
    position: solomonPosition,
    ticksPerFrame: 5,
  }),
})
const template = Object.freeze({
  geometrySha256: boneyardGeometrySha256(scene),
  scene,
  sourceLabel: 'stock/data/levels/tutorial.boneyard',
  sourceSha256: createHash('sha256').update(bytes).digest('hex'),
})

const source = [
  '// Generated by tools/build-stock-tutorial-boneyard.mjs from exact retail data.',
  '// Do not hand-edit. Scenario recipes/scripts live in native-tutorial.ts.',
  '/* oxlint-disable no-loss-of-precision */',
  "import type { NativeBoneyardTemplate } from '../core-kernels/boneyard.ts'",
  '',
  `export const STOCK_TUTORIAL_BONEYARD: NativeBoneyardTemplate = ${JSON.stringify(template)}`,
  '',
].join('\n')

await writeFile(outputPath, source)
process.stdout.write(
  `${relative(process.cwd(), outputPath)}: ${template.sourceSha256} ${template.geometrySha256}\n`,
)
